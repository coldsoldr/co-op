#!/usr/bin/env python3
"""Generate core/include/coop_strip_tables.h: the constant tables of the per-tape channel strip
(docs/channel-strip.md). Stdlib only, Python 3.8.

The firmware has no FPU and no libm, so everything the strip needs from transcendental functions
comes from these tables: EQ frequency steps (cos/sin of w0), gain steps (A, 1/A, sqrt A), Q steps,
the compressor's log2/exp2 and time constants, the saturator's shaping curves and drive gains.

    python3 tools/gen_strip_tables.py > core/include/coop_strip_tables.h

Copyright (C) 2026 coldsoldr. GPL-3.0-or-later with the OP-1 firmware permission.
"""
import math
import sys

FS = 44100.0
SUB = 16                     # compressor detector sub-block (samples)


def q(v, frac):
    r = int(round(v * (1 << frac)))
    lo, hi = -(1 << 31), (1 << 31) - 1
    return max(lo, min(hi, r))


def emit(name, ctype, vals, per_line=8):
    out = ["static const %s %s[%d] = {" % (ctype, name, len(vals))]
    for i in range(0, len(vals), per_line):
        out.append("    " + ", ".join(str(v) for v in vals[i:i + per_line]) + ",")
    out.append("};")
    return "\n".join(out)


def main():
    parts = []
    parts.append("/* Generated by tools/gen_strip_tables.py -- do not edit. Tables for coop_strip.h\n"
                 " * (docs/channel-strip.md). Copyright (C) 2026 coldsoldr. GPL-3.0-or-later with the OP-1\n"
                 " * firmware permission. */")
    parts.append("#ifndef COOP_STRIP_TABLES_H\n#define COOP_STRIP_TABLES_H\n#include <stdint.h>")

    # ---- EQ frequency: 120 steps of 1/12 octave from 20 Hz (20 .. 19.9k) ----
    nf = 120
    freqs = [20.0 * 2.0 ** (i / 12.0) for i in range(nf)]
    parts.append("#define STRIP_EQ_NFREQ %d" % nf)
    parts.append(emit("strip_eq_hz", "uint16_t", [int(round(f)) for f in freqs], 12))
    parts.append(emit("strip_eq_cos", "int32_t", [q(math.cos(2 * math.pi * f / FS), 30) for f in freqs]))
    parts.append(emit("strip_eq_sin", "int32_t", [q(math.sin(2 * math.pi * f / FS), 30) for f in freqs]))

    # ---- EQ gain: half-dB steps -18 .. +18 dB (index 0 = -18 dB, 36 = 0 dB, 72 = +18 dB) ----
    ng = 73
    gains = [(i - 36) * 0.5 for i in range(ng)]
    parts.append("#define STRIP_EQ_NGAIN %d\n#define STRIP_EQ_GAIN0 36" % ng)
    parts.append(emit("strip_eq_A", "int32_t", [q(10 ** (g / 40.0), 28) for g in gains]))
    parts.append(emit("strip_eq_Ainv", "int32_t", [q(10 ** (-g / 40.0), 28) for g in gains]))
    parts.append(emit("strip_eq_sqrtA", "int32_t", [q(10 ** (g / 80.0), 28) for g in gains]))

    # ---- EQ Q: 24 log steps 0.3 .. 10 ----
    nq = 24
    qs = [0.3 * (10.0 / 0.3) ** (i / (nq - 1.0)) for i in range(nq)]
    parts.append("#define STRIP_EQ_NQ %d" % nq)
    parts.append(emit("strip_eq_q100", "uint16_t", [int(round(v * 100)) for v in qs], 12))
    parts.append(emit("strip_eq_inv2q", "int32_t", [q(1.0 / (2.0 * v), 30) for v in qs]))

    # ---- compressor: log2(1 + i/256) and 2^(i/256), Q16 / Q30, 257 entries each ----
    parts.append(emit("strip_log2_tab", "int32_t", [q(math.log2(1 + i / 256.0), 16) for i in range(257)]))
    parts.append(emit("strip_exp2_tab", "int32_t", [q(2 ** (i / 256.0), 30) for i in range(257)]))

    # attack 0.1 .. 100 ms, release 10 .. 2000 ms, 32 log steps; one-pole coef at the sub-block rate, Q31
    na = 32
    att = [0.1 * (1000.0) ** (i / (na - 1.0)) for i in range(na)]
    rel = [10.0 * (200.0) ** (i / (na - 1.0)) for i in range(na)]
    def coef(ms):
        tau = ms / 1000.0
        c = 1.0 - math.exp(-SUB / (tau * FS))
        return min((1 << 31) - 1, q(c, 31))
    parts.append("#define STRIP_COMP_SUB %d\n#define STRIP_COMP_NTIME %d" % (SUB, na))
    parts.append(emit("strip_att_ms10", "uint16_t", [int(round(v * 10)) for v in att], 12))
    parts.append(emit("strip_rel_ms", "uint16_t", [int(round(v)) for v in rel], 12))
    parts.append(emit("strip_att_coef", "int32_t", [coef(v) for v in att]))
    parts.append(emit("strip_rel_coef", "int32_t", [coef(v) for v in rel]))

    # ratio: 1, 1.5, 2, 3, 4, 6, 8, 12, 20, inf -> slope (1 - 1/ratio), Q16
    ratios = [1.0, 1.5, 2.0, 3.0, 4.0, 6.0, 8.0, 12.0, 20.0, float("inf")]
    parts.append("#define STRIP_COMP_NRATIO %d" % len(ratios))
    parts.append(emit("strip_ratio_x10", "uint16_t", [0 if math.isinf(r) else int(round(r * 10)) for r in ratios], 10))
    parts.append(emit("strip_ratio_slope", "int32_t", [q(1.0 - (0.0 if math.isinf(r) else 1.0 / r), 16) for r in ratios]))

    # ---- saturator: shaping curves over the driven value x in [-4, 4], 513 points, int16 ----
    xs = [-4.0 + 8.0 * i / 512.0 for i in range(513)]
    tb = 0.3
    def tape(x):
        return math.tanh(x)
    def tube(x):
        y = math.tanh(x + tb) - math.tanh(tb)
        return y / (1.0 + math.tanh(tb))          # -1 at the bottom, the top clips earlier: even harmonics
    def diode(x):
        return x / (1.0 + abs(x) ** 6) ** (1.0 / 6.0)
    for name, f in (("strip_sat_tape", tape), ("strip_sat_tube", tube), ("strip_sat_diode", diode)):
        parts.append(emit(name, "int16_t", [max(-32767, min(32767, int(round(f(x) * 32767)))) for x in xs], 16))

    # drive 0..100 -> pre-gain 0 .. +24 dB (Q24) and output compensation 1/sqrt(gain) (Q15)
    dg = [10 ** (d * 24.0 / 100.0 / 20.0) for d in range(101)]
    parts.append(emit("strip_drive_gain", "int32_t", [q(g, 24) for g in dg]))
    parts.append(emit("strip_drive_comp", "int16_t", [int(round(32767 / math.sqrt(g))) for g in dg], 12))

    parts.append("#endif")
    sys.stdout.write("\n\n".join(parts) + "\n")


if __name__ == "__main__":
    main()
