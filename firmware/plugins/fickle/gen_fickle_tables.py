#!/usr/bin/env python3
"""fickle's constant tables (fickle_tables.h): the clock's increments and filter coefficients, the exp2 fraction, the
equal-power mix, the slip speeds and their longest refresh, the reverb taps. Float lives here, never in the plugin.

    python3 gen_fickle_tables.py fickle_tables.h

Stdlib only, Python 3.8.
"""
import math
import sys

FS = 44100.0
CLOCK_LO, CLOCK_OCT = 2000.0, 4.0          # the clock: 2 kHz .. 32 kHz, exponential over the knob
IN_FC, OUT_FC = 0.42, 0.45                 # the input pre-filter and each output smoothing pole, x the clock
WET_PAIRS = 16384
SLIP_X = 256                               # the slip heads' crossfade (clock samples)

# slip speeds, reverse first (semitone-ish ratios: octaves, fifths, fourths, a tone)
SLIP = [-2.0, -2 ** (7 / 12), -1.0, -2 ** (-5 / 12), -0.5,
        0.5, 2 ** (-7 / 12), 2 ** (-5 / 12), 2 ** (-2 / 12), 1.0, 2 ** (2 / 12), 2 ** (5 / 12), 2 ** (7 / 12), 2.0]

# reverb taps: the fraction of the size each tap sits at, and its gain on L and R (each side's |gains| sum to 1)
TAP_AT = [0.113, 0.229, 0.371, 0.523, 0.709, 1.0]
TAP_L = [0.30, -0.24, 0.18, -0.13, 0.09, -0.06]
TAP_R = [0.26, 0.22, -0.18, 0.14, -0.11, 0.09]


def clock_hz(i):
    return CLOCK_LO * 2 ** (CLOCK_OCT * i / 32.0)


def one_pole(fc):
    return 1.0 - math.exp(-2 * math.pi * min(fc, 0.49 * FS) / FS)


def q(v, scale, hi=None):
    r = int(round(v * scale))
    return min(r, hi) if hi is not None else r


def slip_rmax(s):
    """The longest refresh (clock samples) at speed s that keeps both heads inside the wet buffer (fickle.cc Slip)."""
    room = WET_PAIRS - 512
    if s > 1:
        r = room / s
    elif s > 0:
        r = (room - SLIP_X) / 2
    else:
        r = room / (abs(s) + 1) - SLIP_X
    return int(r)


def arr(name, ctype, vals, per=8):
    lines = ['const %s %s[%d] = {' % (ctype, name, len(vals))]
    for i in range(0, len(vals), per):
        lines.append('    ' + ', '.join(str(v) for v in vals[i:i + per]) + ',')
    lines.append('};')
    return '\n'.join(lines)


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    out = []
    out.append('/* fickle\'s tables: generated by gen_fickle_tables.py, do not edit. */')
    out.append('#ifndef COOP_FICKLE_TABLES_H_')
    out.append('#define COOP_FICKLE_TABLES_H_')
    out.append('#include <stdint.h>')
    out.append('namespace fickle {')
    out.append('/* The clock at knob c = i x 1024: the phase increment a 44.1 kHz sample (Q16), 2 kHz .. 32 kHz. */')
    out.append(arr('kClockInc', 'int32_t', [q(clock_hz(i) / FS, 65536) for i in range(33)]))
    out.append('/* The input pre-filter (one pole at %.2f x the clock: gentle, the clock aliases) and each of the two '
               'output smoothing poles (%.2f x the clock), Q15. */' % (IN_FC, OUT_FC))
    out.append(arr('kClockAIn', 'int32_t', [q(one_pole(IN_FC * clock_hz(i)), 32768, 32767) for i in range(33)]))
    out.append(arr('kClockAOut', 'int32_t', [q(one_pole(OUT_FC * clock_hz(i)), 32768, 32767) for i in range(33)]))
    out.append('/* 2^(j / 32) in Q15, j 0..32. */')
    out.append(arr('kExp2Frac', 'int32_t', [q(2 ** (j / 32.0), 32768) for j in range(33)]))
    out.append('/* sin(pi / 2 x i / 16) in Q15: the equal-power mix (cos from the other end). */')
    out.append(arr('kQuarterSin', 'int32_t', [q(math.sin(math.pi / 2 * i / 16), 32767) for i in range(17)]))
    out.append('/* Slip: the speeds (Q16 clock samples a clock sample, negative = reverse) and the longest refresh each '
               'allows. */')
    out.append('const int32_t kSlipSteps = %d;' % len(SLIP))
    out.append(arr('kSlipSpeed', 'int32_t', [q(s, 65536) for s in SLIP]))
    out.append(arr('kSlipRmax', 'int32_t', [slip_rmax(s) for s in SLIP]))
    out.append('/* Reverb: the taps (Q15 of the size) and their gains on L and R (Q15). */')
    out.append('const int32_t kTaps = %d;' % len(TAP_AT))
    out.append(arr('kTapAt', 'int32_t', [q(a, 32768, 32767) for a in TAP_AT]))
    out.append(arr('kTapL', 'int16_t', [q(g, 32768) for g in TAP_L]))
    out.append(arr('kTapR', 'int16_t', [q(g, 32768) for g in TAP_R]))
    out.append('}  // namespace fickle')
    out.append('#endif')
    with open(sys.argv[1], 'w', encoding='utf-8', newline='\n') as f:
        f.write('\n'.join(out) + '\n')
    print('%s written' % sys.argv[1])


if __name__ == '__main__':
    main()
