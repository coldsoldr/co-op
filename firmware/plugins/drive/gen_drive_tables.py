#!/usr/bin/env python3
"""Generate src/drive_tables.h: DRIVE's four tables that upstream computes with constexpr double maths.

    python3 -I gen_drive_tables.py > src/drive_tables.h

coop allows no float or double in a plugin's source, not even at compile time (guide/plugin-guidelines.md 2.1), so
the tables te-op1-cfw's ports/fx/src/drive/drive.cc builds with constexpr Exp / Sqrt / Sin are generated here with
the same operations in the same order (Python floats are IEEE doubles, as the compiler's constant folding is).
tests/host/drive (`make tables`) compares every entry against upstream's constexpr tables. Stdlib only, Python 3.8.

Copyright (C) 2026 coldsoldr. GPL-3.0-or-later with the OP-1 firmware permission.
"""

K_PI = 3.14159265358979323846
K_LN10 = 2.30258509299404568
K_LN2 = 0.69314718055994531
K_DRIVE_DB = 36.0
K_BIAS_MAX = 0.5
K_REF_LEVEL = 0.25


def exp_(x):
    halvings = 0
    while x > 0.25 or x < -0.25:
        x *= 0.5
        halvings += 1
    term = 1.0
    s = 1.0
    for i in range(1, 16):
        term *= x / i
        s += term
    for _ in range(halvings):
        s *= s
    return s


def sqrt_(x):
    if x <= 0:
        return 0.0
    r = x if x > 1 else 1.0
    for _ in range(60):
        r = 0.5 * (r + x / r)
    return r


def sin_(x):
    term = x
    s = x
    for i in range(1, 20):
        term *= -x * x / ((2 * i) * (2 * i + 1))
        s += term
    return s


def round_(x):
    return int(x - 0.5) if x < 0 else int(x + 0.5)   # static_cast<int32_t>: truncates toward 0


def gain_k(knob):
    return 2.0 * exp_(knob * K_DRIVE_DB / 20.0 * K_LN10) / 1.875


def shape_d(u):
    if u > 1:
        u = 1.0
    if u < -1:
        u = -1.0
    t = u * u
    return u * (15.0 - 10.0 * t + 3.0 * t * t) / 16.0


def int16(v):
    v &= 0xffff
    return v - 0x10000 if v & 0x8000 else v


def tables():
    k = [round_(65536.0 * gain_k(i / 32.0)) for i in range(33)]
    k.append(k[32])
    inv_k = [int16(round_(32768.0 / gain_k(i / 32.0))) for i in range(33)]
    inv_k.append(inv_k[32])
    tilt = [int16(round_(8192.0 * exp_((i - 16) / 16.0 * K_LN2))) for i in range(33)]
    tilt.append(tilt[32])
    n = 256
    s = []
    for j in range(n):
        ph = 2.0 * K_PI * j / n
        s.append(sin_(ph) if ph <= K_PI else -sin_(2.0 * K_PI - ph))
    makeup = []
    for i in range(17):
        g = gain_k(i / 16.0)
        row = []
        for j in range(9):
            b = K_BIAS_MAX * j / 8.0
            sm = 0.0
            sm2 = 0.0
            for q in range(n):
                y = 2.0 * shape_d(g * K_REF_LEVEL * 0.5 * s[q] + b)
                sm += y
                sm2 += y * y
            mean = sm / n
            rms = sqrt_(sm2 / n - mean * mean)
            m = K_REF_LEVEL / sqrt_(2.0) / rms
            v = round_(8192.0 * m)
            row.append(int16(min(v, 32767)))
        makeup.append(row)
    tone_k = round_(32768.0 * (1.0 - exp_(-2.0 * K_PI * 1000.0 / 44100.0)))
    dc_k = round_(32768.0 * 2.0 * K_PI * 10.0 / 44100.0)
    return k, inv_k, tilt, makeup, tone_k, dc_k


def row(vals, per=12):
    return '\n'.join('    ' + ', '.join(str(v) for v in vals[i:i + per]) + ',' for i in range(0, len(vals), per))


def main():
    k, inv_k, tilt, makeup, tone_k, dc_k = tables()
    out = ['// Generated by gen_drive_tables.py: do not edit. DRIVE\'s tables (te-op1-cfw ports/fx/src/drive/drive.cc',
           '// builds them with constexpr double maths; coop allows no double, so they are integers here).',
           '// Copyright (C) 2026 coldsoldr. GPL-3.0-or-later with the OP-1 firmware permission.',
           '#ifndef COOP_DRIVE_SRC_DRIVE_TABLES_H_', '#define COOP_DRIVE_SRC_DRIVE_TABLES_H_', '', '#include <stdint.h>', '',
           'namespace op1fx {', 'namespace drive_tables {', '',
           '// K (Q16) over the drive knob: 2 x 10^(36 x / 20) / 1.875, 33 points and the last again.',
           'const int32_t kK[34] = {', row(k), '};',
           '// 1 / K, Q15.', 'const int16_t kInvK[34] = {', row(inv_k), '};',
           '// The tilt\'s gains: 2^(-1 .. 1) over 0..32768, Q13.', 'const int16_t kTilt[34] = {', row(tilt), '};',
           '// The auto-level gain (Q13), drive (17) x bias (9): a -12 dBFS sine\'s RMS in over the wet\'s RMS out.',
           'const int16_t kMakeup[17][9] = {']
    out += ['  {' + ', '.join(str(v) for v in r) + '},' for r in makeup]
    out += ['};', '// The tilt\'s one-pole (1 kHz) and the DC blocker\'s (10 Hz) coefficients, Q15 (drive_bfin.S has both).',
            f'const int32_t kToneK = {tone_k};', f'const int32_t kDcK = {dc_k};', '',
            '}  // namespace drive_tables', '}  // namespace op1fx', '', '#endif  // COOP_DRIVE_SRC_DRIVE_TABLES_H_']
    print('\n'.join(out))


if __name__ == '__main__':
    main()
