#!/usr/bin/env python3
"""Generate src/halfband_bfin.S, the 4x upsampler's half-band stage (rings.cc Upsampler) for the Blackfin:

    python3 -I gen_halfband_asm.py > src/halfband_bfin.S

Output m (0..31) of the 22.05 -> 44.1 kHz stage is a symmetric 24-tap FIR over the 16-bit samples x[m+1 .. m+24]:
    acc = 8192 + sum_k T[k] x[m+1+k],   T[k] = c[11-k] (k < 12), c[k-12] (k >= 12)     (c: src/halfband_taps.h)
    mid[3+2m] = x[m+12],   mid[4+2m] = acc >> 14
the C loop's exact integer arithmetic (every product 16 x 16, the sum inside 32 bits: no accumulator saturates).
The twelve taps sit in R2..R7 as 16-bit halves (c0 c1 | c2 c3 | ... | c10 c11), the samples are read as aligned 32-bit
pairs, so the odd outputs read x and the even ones a copy shifted by one sample (xs[i] = x[i+1]). One product a cycle;
each pair's second multiply carries the next pair's load; the even pairs sum in A0, the odd ones in A1 (an
accumulator moves only to a register of its own parity), added at the end. Packet shapes: a MAC alone, and
`Rn = (An += Rn.x * Rn.x) (IS) || Rn = [In++] || NOP` (the stock's integer-MAC-with-load form; tools/asm_lint.py).
"""

TAP_REG = lambda j: 'R%d.%s' % (2 + j // 2, 'L' if j % 2 == 0 else 'H')   # c_j


def body():
    out = []
    for i in range(12):                       # sample pair i: x[base+2i] (.L), x[base+2i+1] (.H)
        x, y, acc = ('R0', 'R1', 'A0') if i % 2 == 0 else ('R1', 'R0', 'A1')
        k0, k1 = 2 * i, 2 * i + 1
        t0 = 11 - k0 if k0 < 12 else k0 - 12
        t1 = 11 - k1 if k1 < 12 else k1 - 12
        out.append('\t%s += %s.L * %s (IS);' % (acc, x, TAP_REG(t0)))
        if i < 11:
            out.append('\t%s = (%s += %s.H * %s) (IS) || %s = [I0++] || NOP;' % (x, acc, x, TAP_REG(t1), y))
        else:
            out.append("\t%s = (%s += %s.H * %s) (IS);   /* the odd pairs' sum */" % (x, acc, x, TAP_REG(t1)))
    return '\n'.join(out)


HEAD = '''/* Generated by gen_halfband_asm.py: do not edit (see there for the arithmetic).
 *
 * void HalfbandAsm(const int16_t* x, const int16_t* xs, int32_t* mid3);
 *   x:    56 samples (24 history + 32 new), 4-byte aligned; xs: x shifted by one (xs[i] = x[i + 1]), aligned
 *   mid3: &mid[3]; writes mid3[0 .. 63]
 * Bit-identical with the C loop in rings.cc (tests/host/rings/halfband_check.cc, in the simulator).
 *
 * Copyright (C) 2026 coldsoldr. GPL-3.0-or-later with the OP-1 firmware permission.
 */

	.section .rodata
	.align 4
.Ltaps:
	.short 10380, -3328, 1846, -1169, 772, -510, 330, -205, 120, -64, 29, -9   /* src/halfband_taps.h, c0..c11 */

	.text
	.align 4
	.global _HalfbandAsm
	.type _HalfbandAsm, STT_FUNC
_HalfbandAsm:
	LINK 0;
	[--SP] = (R7:4, P5:3);
	[--SP] = LC0;
	[--SP] = LT0;
	[--SP] = LB0;
	P3 = R0;                        /* x */
	P4 = R1;                        /* xs */
	P5 = R2;                        /* mid3 */
	P2.H = .Ltaps;
	P2.L = .Ltaps;
	R2 = [P2];
	R3 = [P2 + 4];
	R4 = [P2 + 8];
	R5 = [P2 + 12];
	R6 = [P2 + 16];
	R7 = [P2 + 20];
	P2 = 16;                        /* outputs a pass */

	/* Pass 1, the odd outputs m = 1, 3 .. 31: base m + 1 is even, so x itself. */
	P0 = P3;
	P0 += 4;                        /* x + 2 = x[m + 1] for m = 1 */
	P1 = P5;
	P1 += 8;                        /* mid3 + 2 m, m = 1 */
	LSETUP (.Lodd_start, .Lodd_end) LC0 = P2;
.Lodd_start:
	OUTPUT
.Lodd_end:
	NOP;

	/* Pass 2, the even outputs m = 0, 2 .. 30: base m + 1 is odd, so xs (xs[m] = x[m + 1]). */
	P0 = P4;
	P1 = P5;
	LSETUP (.Leven_start, .Leven_end) LC0 = P2;
.Leven_start:
	OUTPUT
.Leven_end:
	NOP;

	LB0 = [SP++];
	LT0 = [SP++];
	LC0 = [SP++];
	(R7:4, P5:3) = [SP++];
	UNLINK;
	RTS;
	.size _HalfbandAsm, .-_HalfbandAsm
'''

OUTPUT = '''I0 = P0;
	A1 = A0 = 0;
	R0 = [I0++];
%s
	R0 = A0 (IS);                   /* the even pairs' sum */
	R1 = R1 + R0;
	R0 = 8192 (X);
	R1 = R1 + R0;
	R1 >>>= 14;                     /* mid[4 + 2m] */
	R0 = W[P0 + 22] (X);            /* x[m + 12]: mid[3 + 2m] */
	[P1] = R0;
	[P1 + 4] = R1;
	P0 += 4;                        /* the next output of this pass: two samples on */
	P1 += 16;''' % body()

print(HEAD.replace('OUTPUT', OUTPUT), end='')
