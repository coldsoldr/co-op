#!/usr/bin/env python3
"""Generate plugins/ensemble/src/ensemble_tables.cc: the ensemble's integer tables.

te-op1-cfw's ensemble (ports/fx/src/ensemble/ensemble.cc) builds its tables at compile time from constexpr double
maths; coop allows no float or double anywhere in a plugin's sources (guide/plugin-guidelines.md 2.1), so the same
maths runs here, in the same order of IEEE double operations, and the results go in as integer literals. The half-rate
path's soft-limit table (te-op1-cfw ports/clouds/src/core/halfband.cc InitSoftLimitTable, from Rings' kSoftLimitQ30)
is precomputed too, so init builds nothing. tests/host/ensemble checks every value against the upstream build.

    python3 -I gen_tables.py [path/to/te-op1-cfw/ports]   (default ../../../../te-op1-cfw/ports from this folder)

Stdlib only, Python 3.8.
"""
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
PORTS = Path(sys.argv[1]) if len(sys.argv) > 1 else HERE.parents[3] / 'te-op1-cfw' / 'ports'

K_PI = 3.14159265358979323846
K_RATE = 22050.0
K_TWO32 = 4294967296.0
EN_SLOW_MAX = 80


def exp_(x):                                   # ensemble.cc Exp, operation for operation
    halvings = 0
    while x > 0.25 or x < -0.25:
        x *= 0.5
        halvings += 1
    term, s = 1.0, 1.0
    for i in range(1, 16):
        term *= x / i
        s += term
    for _ in range(halvings):
        s *= s
    return s


def sin_(x):                                   # ensemble.cc Sin
    while x > K_PI:
        x -= 2.0 * K_PI
    while x < -K_PI:
        x += 2.0 * K_PI
    term, s = x, x
    for i in range(1, 14):
        term *= -x * x / ((2.0 * i) * (2.0 * i + 1.0))
        s += term
    return s


def round_(x):                                 # ensemble.cc Round: half away from zero, then truncate
    return int(x - 0.5 if x < 0 else x + 0.5)


K_LN005 = -2.9957322735539909
K_LN160 = 5.0751738152338266


def rate_hz(x):
    return exp_(K_LN005 + x * K_LN160)


K_PITCH_CAP = 0.02 * K_RATE / (2.0 * K_PI)


def slow_cap(f):
    return K_PITCH_CAP / f if K_PITCH_CAP / f < EN_SLOW_MAX else EN_SLOW_MAX


def u32(x):                                    # static_cast<uint32_t>(double) for 0 <= x < 2^32
    return int(x)


def soft_limit():
    text = (PORTS / 'rings' / 'src' / 'fixed_tables.cc').read_text()
    m = re.search(r'kSoftLimitQ30\[257\]\s*=\s*\{([^}]*)\}', text)
    q30 = [int(v) for v in m.group(1).replace('\n', ' ').split(',') if v.strip()]
    assert len(q30) == 257
    value = [min((v + (1 << 13)) >> 14, 32767) for v in q30]
    step = [value[i + 1] - value[i] for i in range(256)]
    return value, step


def xfade(name):
    text = (PORTS / 'clouds' / 'src' / 'core' / 'clouds_tables.cc').read_text()
    m = re.search(name + r'\[18\]\s*=\s*\{([^}]*)\}', text)
    vals = [int(v) for v in m.group(1).replace('\n', ' ').split(',') if v.strip()]
    assert len(vals) == 18
    return vals


def rows(vals, per=8, indent='  '):
    out = []
    for i in range(0, len(vals), per):
        out.append(indent + ', '.join(str(v) for v in vals[i:i + per]) + ',')
    return '\n'.join(out)


def main():
    rate = [u32(rate_hz(i / 32.0) * K_TWO32 / K_RATE + 0.5) for i in range(33)]
    cap = [round_(256.0 * slow_cap(rate_hz(i / 32.0))) for i in range(33)]
    sine = [round_(32767.0 * sin_(2.0 * K_PI * i / 1024.0)) for i in range(1025)]
    fast = u32(6.57 * K_TWO32 / K_RATE + 0.5)
    value, step = soft_limit()
    src = f"""// Generated by gen_tables.py. Do not edit.
// The ensemble's tables (te-op1-cfw ports/fx/src/ensemble/ensemble.cc, there constexpr double maths) and the half-rate
// path's soft-limit table (ports/clouds/src/core/halfband.cc InitSoftLimitTable), as integers: coop plugins have no
// float or double anywhere (guide/plugin-guidelines.md 2.1).

#include "src/ensemble_tables.h"

namespace coop_ensemble {{

// The slow LFO's phase increment per sample at rate i / 32: 0.05 x 160^x Hz at 22050 Hz, x 2^32.
const uint32_t kRateTable[33] = {{
{rows(rate, 6)}
}};

// The sweep's peak at depth 1, Q8 samples: 80, or less where a 2 % pitch deviation caps it.
const int32_t kCapTable[33] = {{
{rows(cap, 11)}
}};

// sin(2 pi i / 1024) x 32767, rounded.
const int16_t kSine[1025] = {{
{rows(sine, 12)}
}};

// 6.57 Hz at 22050 Hz, x 2^32: the vibrato.
const uint32_t kEnsembleFastIncrement = {fast}u;

// 2 x stmlib's SoftLimit over [0, 4] as int16 output samples, clipped, and the steps between them.
const SoftLimitTable kSoftLimit = {{
  {{
{rows(value, 12, '    ')}
  }},
  {{
{rows(step, 12, '    ')}
  }},
}};

// Clouds' lut_xfade_in / lut_xfade_out, Q31, + 1 guard (copied from te-op1-cfw ports/clouds/src/core/clouds_tables.cc).
const int32_t kXfadeInQ31[18] = {{
{rows(xfade('kXfadeInQ31'), 6)}
}};
const int32_t kXfadeOutQ31[18] = {{
{rows(xfade('kXfadeOutQ31'), 6)}
}};

}}  // namespace coop_ensemble
"""
    (HERE / 'src' / 'ensemble_tables.cc').write_text(src)
    print('fast increment', fast)


if __name__ == '__main__':
    main()
