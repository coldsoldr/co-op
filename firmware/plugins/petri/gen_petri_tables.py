#!/usr/bin/env python3
"""petri's constant tables (src/petri_tables.h): the grain envelopes, 2^x, the filter's coefficients.

    python3 gen_petri_tables.py src/petri_tables.h

Every number the DSP needs that would otherwise take float or a transcendental function at run time: the plugin has
no float at all (guide/plugin-guidelines.md section 2.1). Stdlib only, Python 3.8.
"""
import math
import sys

FS = 22050.0             # the engine's rate (2:1 under the bus)
SHAPE_POINTS = 65        # 64 segments + the end point
FC_LO, FC_HI = 150.0, 10000.0
Q_TOP, Q_BOTTOM = 0.85, 1.7   # the filter's Q at the top of the knob and at the bottom (rising as it closes)


def q15(v):
    return max(-32768, min(32767, int(round(v * 32767))))


def shapes():
    out = []
    n = SHAPE_POINTS - 1
    # 0 hann: sin^2, the overlap-add window
    out.append(('hann', [math.sin(math.pi * i / n) ** 2 for i in range(n + 1)]))
    # 1 trap: fades of 1/8 each end (raised cosine), flat between: a loop that repeats
    def trap(fade):
        v = []
        for i in range(n + 1):
            x = i / n
            if x < fade:
                v.append(0.5 - 0.5 * math.cos(math.pi * x / fade))
            elif x > 1 - fade:
                v.append(0.5 - 0.5 * math.cos(math.pi * (1 - x) / fade))
            else:
                v.append(1.0)
        return v
    out.append(('trap', trap(1 / 8)))
    # 2 gate: fades of 1/32: a slice in a sequence, a glitch block
    out.append(('gate', trap(1 / 32)))
    # 3 perc: a 1/32 attack, then an exponential fall to -40 dB, faded to 0 over the last 1/16
    v = []
    for i in range(n + 1):
        x = i / n
        a = min(1.0, x * 32)
        d = math.exp(-4.6 * max(0.0, x - 1 / 32) / (1 - 1 / 32))
        f = min(1.0, (1 - x) * 16)
        v.append(a * d * f)
    out.append(('perc', v))
    # 4 swell: rises (squared) to 1 at 80 %, falls in a raised cosine
    v = []
    for i in range(n + 1):
        x = i / n
        if x < 0.8:
            v.append((x / 0.8) ** 2)
        else:
            v.append(0.5 + 0.5 * math.cos(math.pi * (x - 0.8) / 0.2))
    out.append(('swell', v))
    # 5 flat: a tap (no envelope; the voice's gain ramps)
    out.append(('flat', [1.0] * (n + 1)))
    for name, s in out:
        s[0] = 0.0 if name != 'flat' else 1.0
        if name != 'flat':
            s[-1] = 0.0
    return out


def exp2():
    # 2^(i / 64), i = 0..64, Q30 (unsigned: the last is 2^31)
    return [int(round(2 ** (i / 64) * (1 << 30))) for i in range(65)]


def svf():
    """The filter knob's 65 points: fc = 150 Hz x (10 kHz / 150 Hz)^x; Q from Q_BOTTOM at 0 to Q_TOP at 1 (exponential
    in x^2, so it rises only in the lower part). The TPT state variable filter's a1, a2, a3 in Q31."""
    rows = []
    for i in range(65):
        x = i / 64
        fc = FC_LO * (FC_HI / FC_LO) ** x
        q = Q_TOP + (Q_BOTTOM - Q_TOP) * (1 - x) ** 2
        g = math.tan(math.pi * fc / FS)
        k = 1 / q
        a1 = 1 / (1 + g * (g + k))
        a2 = g * a1
        a3 = g * a2
        rows.append(tuple(min((1 << 31) - 1, int(round(a * (1 << 31)))) for a in (a1, a2, a3)))
    return rows


def fmt(vals, per=12, indent='  '):
    lines = []
    for i in range(0, len(vals), per):
        lines.append(indent + ', '.join(str(v) for v in vals[i:i + per]) + ',')
    return '\n'.join(lines)


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    out = ['// Generated by plugins/petri/gen_petri_tables.py. Do not edit.',
           '// Copyright (C) 2026 coldsoldr. GPL-3.0-or-later with the OP-1 firmware permission.',
           '#ifndef COOP_PETRI_TABLES_H_', '#define COOP_PETRI_TABLES_H_', '', '#include <stdint.h>', '',
           'namespace petri {', '']
    sh = shapes()
    out.append('// The grain envelopes, %d points each, Q15: %s.' % (SHAPE_POINTS, ', '.join(n for n, _ in sh)))
    out.append('const int16_t kShapes[%d][%d] = {' % (len(sh), SHAPE_POINTS))
    for name, s in sh:
        out.append('  {  // %s' % name)
        out.append(fmt([q15(v) for v in s], indent='    '))
        out.append('  },')
    out.append('};')
    out.append('')
    out.append('// 2^(i / 64), Q30, i = 0..64.')
    out.append('const uint32_t kExp2Q30[65] = {')
    out.append(fmt(exp2(), per=6))
    out.append('};')
    out.append('')
    out.append('// The filter knob (65 points over 0..32767): fc %g Hz .. %g kHz exponential at %g Hz, Q %g .. %g; the'
               % (FC_LO, FC_HI / 1000, FS, Q_BOTTOM, Q_TOP))
    out.append('// TPT state variable filter\'s a1 = 1 / (1 + g (g + k)), a2 = g a1, a3 = g a2 (g = tan(pi fc / fs), k = 1 / Q), Q31.')
    out.append('const int32_t kSvf[65][3] = {')
    for r in svf():
        out.append('  { %d, %d, %d },' % r)
    out.append('};')
    out += ['', '}  // namespace petri', '', '#endif  // COOP_PETRI_TABLES_H_', '']
    with open(sys.argv[1], 'w', encoding='utf-8', newline='\n') as f:
        f.write('\n'.join(out))
    print('%s written' % sys.argv[1])


if __name__ == '__main__':
    main()
