// The tape echo port's table generator: prints plugins/tape_echo/src/tape_echo_tables.h from te-op1-cfw's own
// constexpr tables (ports/fx/src/tape_echo/tape_echo.cc, evaluated by the compiler in double, which coop's plugin
// sources may not contain: guidelines §2.1) and the half-rate mix's soft-limit table (ports/clouds/src/core/halfband.cc
// InitSoftLimitTable over ports/rings' kSoftLimitQ30), so the plugin carries the same numbers as integer literals.
//   make -C tests/host/tape_echo tables      (rewrites ../../../plugins/tape_echo/src/tape_echo_tables.h)
//
