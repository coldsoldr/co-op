#include <cstdio>

#include "src/tape_echo/tape_echo.cc"      // the anonymous namespace's tables are this translation unit's
#include "src/core/halfband.h"

namespace op1fx {
namespace {

void Row(const char* type, const char* name, const int32_t* v, int n) {
  std::printf("const %s %s[%d] = {", type, name, n);
  for (int i = 0; i < n; ++i) std::printf("%s%d,", i % 12 ? " " : "\n  ", static_cast<int>(v[i]));
  std::printf("\n};\n");
}

template <class T>
void Row16(const char* name, const T* v, int n) {
  int32_t w[300];
  for (int i = 0; i < n; ++i) w[i] = v[i];
  Row("int16_t", name, w, n);
}

}  // namespace

void Dump() {
  std::printf("// Generated by tests/host/tape_echo/gen_tables.cc from te-op1-cfw ports/fx/src/tape_echo/tape_echo.cc\n"
              "// (its constexpr tables) and ports/clouds/src/core/halfband.cc (InitSoftLimitTable). Do not edit.\n\n"
              "#ifndef COOP_TAPE_ECHO_TABLES_H_\n#define COOP_TAPE_ECHO_TABLES_H_\n\n#include <cstdint>\n\n"
              "namespace op1fx {\nnamespace tables {\n\n");
  std::printf("// TIME: head 3's delay in Q4 samples at 22050 Hz, 661.5 x 50^(i / 32).\n");
  Row("int32_t", "kTime", kTimeTable.v, 33);
  std::printf("// Tape loss: k = 1 - exp(-2 pi fc / fs), fc = 9 kHz x 0.2^(i / 32), Q15.\n");
  Row("int32_t", "kLoss", kLossTable.v, 33);
  std::printf("// Low cut: fc = 40 x 2.75^(i / 32) Hz, Q15.\n");
  Row("int32_t", "kLowCut", kLowCutTable.v, 33);
  std::printf("// 1 / drive = 1 / (1 + i / 32), Q15.\n");
  Row("int32_t", "kInvDrive", kInvDriveTable.v, 33);
  std::printf("// A full sine cycle, Q15, 256 segments.\n");
  Row16("kSine", kSine.v, 257);
  std::printf("// The saturation: 32767 sin(2 u), u = (i - 128) / 128, flat beyond 2 u = pi / 2.\n");
  Row16("kSat", kSat.v, 257);
  op1clouds::SoftLimitTable t;
  op1clouds::InitSoftLimitTable(&t);
  std::printf("// The half-rate mix's soft limit: 2 x stmlib SoftLimit over [0, 4], clipped (257), then its steps (256).\n");
  Row16("kSoftLimitValue", t.value, 257);
  Row16("kSoftLimitStep", t.step, 256);
  std::printf("\n}  // namespace tables\n}  // namespace op1fx\n\n#endif  // COOP_TAPE_ECHO_TABLES_H_\n");
}

}  // namespace op1fx

int main() {
  op1fx::Dump();
  return 0;
}
