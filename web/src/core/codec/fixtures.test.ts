import { describe, it, expect } from 'vitest';
import { readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { buildFixtures } from '../../../test/fixtures/build-fixtures';
import { firstDifference } from '../../../test/first-difference';

const committed = (name: string): Uint8Array =>
  new Uint8Array(readFileSync(fileURLToPath(new URL(`../../../test/fixtures/${name}`, import.meta.url))));

// Guards against editing test/fixtures/meta.ts (or the generator) without running `pnpm fixtures`.
describe('committed fixtures match the generator', () => {
  const generated = buildFixtures();

  it('generates the four known fixtures', () => {
    expect([...generated.keys()].sort()).toEqual(
      ['drum-boombap.aif', 'no-metadata.aif', 'synth-cluster.aif', 'synth-sampler-sowt.aif'],
    );
  });

  it.each([...generated.keys()])('%s on disk equals the generated bytes', (name) => {
    expect(firstDifference(committed(name), generated.get(name)!), name).toBe(-1);
  });
});
